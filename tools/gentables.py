w('#include "qfs.h"')
w("")

# --- seno: 1024 entradas, vuelta completa, Q14 -----------------------
w("const s16 sin_tab[1024] = {")
vals = [int(round(math.sin(2 * math.pi * i / 1024) * 16384)) for i in range(1024)]
vals = [max(-16384, min(16384, v)) for v in vals]
for i in range(0, 1024, 16):
    w("  " + ",".join(str(v) for v in vals[i:i + 16]) + ",")
w("};")

# --- atan(i/256) en BAM16 (65536 = 360 grados), i = 0..256 ------------
w("const u16 atan_tab[257] = {")
vals = [int(round(math.atan(i / 256) * 65536 / (2 * math.pi))) for i in range(257)]
for i in range(0, 257, 16):
    w("  " + ",".join(str(v) for v in vals[i:i + 16]) + ",")
w("};")

# --- atmosfera ISA cada 1000 m (0..16000): sigma (densidad) y delta (presion), Q16
sig, dlt = [], []
for i in range(17):
    h = i * 1000.0
    if h <= 11000:
        T = 288.15 - 0.0065 * h
        d = (T / 288.15) ** 5.2559
        s = (T / 288.15) ** 4.2559
    else:
        T = 216.65
        d11 = (216.65 / 288.15) ** 5.2559
        d = d11 * math.exp(-9.80665 * (h - 11000) / (287.05 * T))
        s = d * 288.15 / T
    sig.append(int(round(s * 65536)))
    dlt.append(int(round(d * 65536)))
w("const s32 atm_sigma[17] = {" + ",".join(map(str, sig)) + "};")
w("const s32 atm_delta[17] = {" + ",".join(map(str, dlt)) + "};")

